#!/usr/bin/env python
"""Regenerate services/core/model_catalog.py from services/core/model_candidates.txt.

Every candidate is inspected against the Hugging Face Hub without downloading weights. Only models
that pass enter the catalog, and existing entries keep their pinned revision so that past campaigns
stay reproducible. Pass --update to move every entry to its latest commit.

    .venv/bin/python scripts/refresh-model-catalog.py [--update]
"""

import pprint
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
sys.path.insert(0, str(ROOT / "services/training-core/src"))

from services.core.contracts import MODEL_PARAMETER_LIMIT  # noqa: E402
from services.core.model_catalog import CATALOG  # noqa: E402
from services.core.model_inspect import Unsupported, inspect  # noqa: E402

CANDIDATES = ROOT / "services/core/model_candidates.txt"
OUTPUT = ROOT / "services/core/model_catalog.py"
HEADER = '''"""Generated by scripts/refresh-model-catalog.py. Edit model_candidates.txt, then run it."""

CATALOG = '''


def main():
    update = "--update" in sys.argv
    catalog, rejected = {}, []
    for line in CANDIDATES.read_text().splitlines():
        repo = line.split("#")[0].strip()
        if not repo:
            continue
        pinned = None if update else CATALOG.get(repo, {}).get("revision")
        try:
            spec = inspect(repo, pinned)
            if spec["parameter_count"] > MODEL_PARAMETER_LIMIT:
                raise Unsupported(f"{spec['parameters']} parameters is above the limit")
        except Unsupported as error:
            rejected.append((repo, str(error).splitlines()[0][:110]))
            print(f"no   {repo}: {rejected[-1][1]}", flush=True)
            continue
        except Exception as error:  # A flaky or odd repo must not stop the sweep.
            rejected.append((repo, f"{type(error).__name__}: {error}".splitlines()[0][:110]))
            print(f"no   {repo}: {rejected[-1][1]}", flush=True)
            continue
        catalog[repo] = {k: v for k, v in spec.items() if k != "id"}
        print(f"yes  {repo} {spec['parameters']} {spec['lora_targets']}", flush=True)
    OUTPUT.write_text(HEADER + pprint.pformat(catalog, width=100, sort_dicts=False) + "\n")
    print(f"\n{len(catalog)} models in the catalog, {len(rejected)} rejected")


if __name__ == "__main__":
    main()
